"""Data quality report: documents what the Pandera schemas only block."""

import pandas as pd

from churn import config


def profile(df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for col in df.columns:
        s = df[col]
        row = {
            "variable": col,
            "dtype": str(s.dtype),
            "fill_rate": round(float(s.notna().mean()), 4),
            "n_unique": int(s.nunique()),
        }
        if pd.api.types.is_numeric_dtype(s) and col != config.TARGET:
            q = s.quantile([0.01, 0.25, 0.5, 0.75, 0.99])
            row |= {
                "mean": round(float(s.mean()), 3),
                "min": float(s.min()),
                "p01": float(q[0.01]),
                "p25": float(q[0.25]),
                "median": float(q[0.5]),
                "p75": float(q[0.75]),
                "p99": float(q[0.99]),
                "max": float(s.max()),
            }
        else:
            top = s.value_counts(normalize=True)
            row |= {"top_value": str(top.index[0]), "top_share": round(float(top.iloc[0]), 4)}
        rows.append(row)
    return pd.DataFrame(rows)


def table_checks(df: pd.DataFrame) -> dict:
    features = df[[c for c in config.FEATURES if c in df.columns]]
    return {
        "rows": len(df),
        "duplicate_ids": int(df[config.ID_COL].duplicated().sum()) if config.ID_COL in df else None,
        "duplicate_rows_pct": round(float(df.drop(columns=[config.ID_COL], errors="ignore").duplicated().mean()), 4),
        "empty_records": int(features.isna().all(axis=1).sum()),
    }


def fill_rate_stability(splits: dict[str, pd.DataFrame]) -> pd.DataFrame:
    """Fill rate per variable in each sample. A null pattern that shows up in only one sample is a red flag."""
    table = pd.DataFrame({name: df.notna().mean() for name, df in splits.items()}).round(4)
    table["max_diff"] = (table.max(axis=1) - table.min(axis=1)).round(4)
    return table.rename_axis("variable").reset_index()


def to_markdown(splits: dict[str, pd.DataFrame]) -> str:
    checks = {name: table_checks(df) for name, df in splits.items()}
    prof = profile(splits["train"].drop(columns=[config.ID_COL]))
    numeric = prof.dropna(subset=["mean"])[["variable", "fill_rate", "mean", "min", "p01", "median", "p99", "max"]]
    categorical = prof[prof["mean"].isna()][["variable", "fill_rate", "n_unique", "top_value", "top_share"]]
    stability = fill_rate_stability(splits)
    unstable = stability[stability["max_diff"] > 0]

    return "\n".join(
        [
            "# Data quality report",
            "",
            "Generated by `churn.data.quality` on the frozen split.",
            "",
            "## Checks per sample",
            "",
            pd.DataFrame(checks).T.rename_axis("sample").reset_index().to_markdown(index=False),
            "",
            "## Numeric variables (train)",
            "",
            numeric.to_markdown(index=False),
            "",
            "## Categorical variables (train)",
            "",
            categorical.to_markdown(index=False),
            "",
            "## Fill rate stability across samples",
            "",
            unstable.to_markdown(index=False)
            if not unstable.empty
            else "Every variable has the same fill rate in every sample.",
            "",
        ]
    )
