"""Model card for the current champion, built from its bundle. Never edited by hand."""

import json
import shutil

import pandas as pd

from churn import config
from churn.data.ingest import X_y, dataframe_hash, load_split
from churn.decision.policy import customer_value, decide
from churn.models.bundle import load_bundle
from churn.models.evaluate import calibration_table, segment_report
from churn.models.promotion import evaluate_on_holdout

LIMITATIONS = [
    "**Static data, simulated time.** Telco has no dates, so there is no real out-of-time sample. "
    "The simulated monthly cohorts act as a pseudo-OOT.",
    "**Simplified customer value.** CLV is monthly charge x 12; no discounting and no churn risk after retention.",
    "**Fixed offer acceptance rate (35%).** In practice it depends on the segment and should come from a "
    "retention experiment with a control group.",
    "**Global calibration.** Platt fixes the average level. Per-segment offsets were tested (notebook 03) and made "
    "holdout calibration worse, so segments are tested for significant bias instead of corrected.",
    "**Fixed holdout.** It reflects the original population and should be refreshed (versioned) from recent "
    "matured labels after a lasting shift.",
]


def _fmt(df: pd.DataFrame) -> str:
    df = df.copy()
    for col in ("n", "decile"):
        if col in df:
            df[col] = df[col].astype(int)
    return df.to_markdown(index=False, floatfmt=".3f")


def write_model_card() -> None:
    champion_dir = config.CHAMPION_DIR
    bundle = load_bundle(champion_dir)
    meta, policy = bundle["metadata"], bundle["policy"]
    test = meta["test_metrics"]
    parity = meta.get("parity_check", {})

    holdout = load_split("holdout")
    X_h, y_h = X_y(holdout)
    proba_h = bundle["model"].predict_proba(X_h)[:, 1]
    contact_h = decide(proba_h, customer_value(X_h), policy)
    hold = evaluate_on_holdout(bundle, holdout)

    segments = segment_report(X_h, y_h, proba_h, contact_h)
    calibration = calibration_table(y_h, proba_h).round(3)
    shap_imp = pd.read_csv(champion_dir / "shap_importance.csv").head(10)
    stress = pd.read_csv(champion_dir / "stress_test.csv")
    manifest = json.loads((config.SPLITS_DIR / "manifest.json").read_text())

    figures = config.REPORTS_DIR / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    for name in ("shap_importance.png", "shap_beeswarm.png"):
        shutil.copy(champion_dir / name, figures / name)

    if policy["rule"] == "expected_value":
        rule = "contact if `p x 35% x CLV > $60` (expected value per customer)"
    else:
        rule = f"contact if `p >= {policy['threshold']}` (global threshold)"
    weak = segments.dropna(subset=["gini"]).nsmallest(3, "gini")[["segment", "value", "n", "gini"]]
    gaps = segments.assign(calib_gap=(segments["mean_predicted"] - segments["churn_rate"]).abs())
    miscalibrated = gaps.nlargest(3, "calib_gap")[
        ["segment", "value", "n", "churn_rate", "mean_predicted", "calibration_z"]
    ]

    lines = [
        f"# Model card: {config.REGISTERED_MODEL_NAME} v{meta['version']}",
        "",
        "Generated by `churn model-card` from the champion's bundle.",
        "",
        "## Summary",
        "",
        "| | |",
        "|---|---|",
        f"| Registry version | v{meta['version']}, alias `champion` |",
        f"| Algorithm | {meta['model']} + Platt calibration on {config.CALIBRATION_FOLDS}-fold out-of-fold scores |",
        f"| MLflow run | `{meta['run_id']}` |",
        f"| Trained because | {meta['trigger']} |",
        f"| Production cohorts used | {', '.join(meta['trained_on_cohorts']) or 'none (initial model)'} |",
        f"| Training rows | {meta['train_rows']:,} (hash `{meta['train_data_hash']}`) |",
        f"| Promotion holdout | {len(holdout):,} customers (hash `{dataframe_hash(holdout)}`) |",
        f"| Parity, trained vs artifact | {'OK' if parity.get('passed') else 'n/a'} "
        f"({parity.get('rows', 0)} rows, max diff {parity.get('max_abs_diff', 0)}) |",
        "",
        "## Purpose and use",
        "",
        "- **Goal:** rank active customers by their probability of cancelling, so the retention team knows "
        "who to make an offer to.",
        f"- **Decision:** {rule}.",
        "- **Primary use:** monthly batch scoring of the customer base. The API serves single lookups.",
        "- **Out of scope:** setting the offer amount, credit decisions, or treating a score as a certainty "
        "about an individual.",
        "",
        "## Population and target",
        "",
        "- **Universe:** all 7,043 customers in IBM Telco Customer Churn, no exclusions.",
        "- **Target:** `churn = 1` if the customer cancelled within the observed period (`Churn = Yes`).",
        f"- **Label maturity:** {config.LABEL_MATURITY_DAYS} days after the snapshot.",
        "",
        "| Sample | Rows | Churn | Hash |",
        "|---|---|---|---|",
        *[f"| {k} | {v['rows']:,} | {v['churn_rate']:.1%} | `{v['hash']}` |" for k, v in manifest.items()],
        "",
        "## Performance",
        "",
        "| Metric | Train | Test | Holdout |",
        "|---|---|---|---|",
        f"| Gini | {test['train_gini']:.3f} | {test['test_gini']:.3f} | {hold['gini']:.3f} |",
        f"| KS | {test['train_ks']:.3f} | {test['test_ks']:.3f} | {hold['ks']:.3f} |",
        f"| ECE | {test['train_ece']:.3f} | {test['test_ece']:.3f} | {hold['ece']:.3f} |",
        f"| Recall of the decision | {test['train_recall']:.3f} | {test['test_recall']:.3f} | {hold['recall']:.3f} |",
        f"| Campaign net value | - | ${test['test_net_value']:,.0f} | ${hold['net_value']:,.0f} |",
        "",
        f"5-fold CV on train: Gini {test['cv_gini_mean']:.3f} +- {test['cv_gini_std']:.3f}. "
        f"Train-test gap: {test['train_gini'] - test['test_gini']:.3f} Gini (max allowed "
        f"{config.MAX_TRAIN_TEST_GINI_GAP}).",
        "",
        "### Decision policy (test)",
        "",
        "| Rule | Net value |",
        "|---|---|",
        f"| Expected value per customer | ${policy['net_value_expected_value_rule']:,.0f} |",
        f"| Best global threshold ({policy['best_threshold']}) | ${policy['net_value_best_threshold']:,.0f} |",
        f"| Default 0.5 | ${policy['net_value_at_0.5']:,.0f} |",
        "",
        f"Chosen rule: **{policy['rule']}**, contacting {policy['contact_rate']:.1%} of customers.",
        "",
        "## Calibration (holdout, by score decile)",
        "",
        f"Test ECE before calibration: {test['test_ece_uncalibrated']:.3f}, after: {test['test_ece']:.3f}.",
        "",
        _fmt(calibration),
        "",
        "## Performance by driver (holdout)",
        "",
        _fmt(segments),
        "",
        "**Weakest segments (discrimination):**",
        "",
        _fmt(weak),
        "",
        "**Largest calibration gaps:**",
        "",
        _fmt(miscalibrated),
        "",
        "`calibration_z` is the gap between observed and predicted churners in standard errors. "
        f"|z| above {config.MAX_SEGMENT_CALIBRATION_Z} (about 5% family-wise over these segments) would mean a real bias; "
        f"the largest here is {segments['calibration_z'].abs().max():.2f}.",
        "",
        "## Drivers (SHAP)",
        "",
        "![SHAP importance](figures/shap_importance.png)",
        "",
        _fmt(shap_imp),
        "",
        "![SHAP beeswarm](figures/shap_beeswarm.png)",
        "",
        "## Sensitivity (+-1 std stress)",
        "",
        _fmt(stress),
        "",
        "- `tenure` is the dominant numeric driver in both directions.",
        "- Under the expected-value rule, `monthly_charges` moves the contact rate more than the score, because it "
        "also changes the customer's value (CLV = charge x 12).",
        "- `total_charges` is roughly `tenure x monthly_charges`. Stressing it alone creates customers that can't "
        "exist (it breaks `avg_monthly_spend`), which is why its response is not monotonic. Don't read it as a "
        "business scenario.",
        "",
        "## Limitations",
        "",
        *[f"- {item}" for item in LIMITATIONS],
        "",
        "## Monitoring plan",
        "",
        "| Control | Frequency | Threshold | Action |",
        "|---|---|---|---|",
        "| Schema and range validation (Pandera) | every batch | any failure | quarantine the batch |",
        f"| PSI per feature and on the score | every batch | >= {config.PSI_RETRAIN} | retraining signal |",
        f"| Realized Gini on matured cohorts (95% CI) | monthly | upper bound < {config.MIN_GINI} | retraining signal |",
        "| Predicted vs actual churn rate | monthly | - | review calibration |",
        f"| Segment calibration (z-test) | per retrain | \\|z\\| > {config.MAX_SEGMENT_CALIBRATION_Z} | gate fails |",
        f"| Challenger promotion | per retrain | wins >= {config.PROMOTION_MIN_WIN_PROBABILITY:.0%} of paired bootstrap "
        f"resamples, Gini >= champion - {config.PROMOTION_GINI_TOLERANCE} | move the `champion` alias |",
        "",
    ]
    (config.REPORTS_DIR / "model_card.md").write_text("\n".join(lines))
